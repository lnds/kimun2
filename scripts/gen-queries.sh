#!/bin/sh
# Writes src/km2/queries.kai from queries/<lang>/<name>.scm, so the
# queries ship inside the binary; kaikai cannot embed a file itself.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/src/km2/queries.kai"
{
  echo "# Generated by scripts/gen-queries.sh from queries/; do not edit."
  echo
  echo "#[doc(\"The query source for a grammar and a query name, or the empty string.\")]"
  echo "pub fn source(grammar: String, name: String) : String = match (grammar, name) {"
  for f in "$root"/queries/*/*.scm; do
    [ -e "$f" ] || continue
    lang=$(basename "$(dirname "$f")")
    name=$(basename "$f" .scm)
    printf '  ("%s", "%s") ->\n    """\n' "$lang" "$name"
    sed 's/^/    /' "$f"
    printf '    """\n'
  done
  echo '  _ -> ""'
  echo "}"
} > "$out"

kai fmt "$out" >/dev/null
